#!/usr/bin/env bash
# Regenerates web/src/abi/*.ts from the Foundry artifacts.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT/contracts"
OUT="$ROOT/web/src/abi"
mkdir -p "$OUT"
for pair in DepegSentinel:src/DepegSentinel.sol PolicyVault:src/PolicyVault.sol PegKeeper:src/PegKeeper.sol \
  MockToken:src/mocks/MockToken.sol MockPair:src/mocks/MockPair.sol DepegDrill:src/mocks/DepegDrill.sol; do
  name="${pair%%:*}"; file="${pair#*:}"
  abi=$(forge inspect "$file:$name" abi --json)
  lower="$(printf '%s' "${name:0:1}" | tr '[:upper:]' '[:lower:]')${name:1}"
  printf '// Generated by scripts/export-abi.sh. Do not edit.\nexport const %sAbi = %s as const;\n' "$lower" "$abi" > "$OUT/$name.ts"
  echo "wrote $OUT/$name.ts"
done
